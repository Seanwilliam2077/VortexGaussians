// UI-only integration check. No calls into __demo and no simulated audience data.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { startServer, launchBrowser, repoRoot } from '../../research/lib/runtime.mjs';

const out = path.resolve(process.argv[2] || 'tracks/validation/runs/art-ui');
await fs.mkdir(out, { recursive: false });
const result = { date: new Date().toISOString(), scope: 'UI integration, not artistic or physical validation', checks: [], errors: [], sourceHashes: {} };
for (const name of ['tracks/art/index.html', 'tracks/art/art.js', 'tracks/art/art.css', 'demo/index.html']) {
  result.sourceHashes[name] = createHash('sha256').update(await fs.readFile(path.join(repoRoot, name))).digest('hex');
}
const server = await startServer();
let browser, page;
const check = (name, details = {}) => result.checks.push({ name, passed: true, ...details });
const waitText = async (selector, text) => {
  const until = Date.now() + 90000;
  while (Date.now() < until) {
    if ((await page.locator(selector).textContent()).includes(text)) return;
    await page.waitForTimeout(200);
  }
  throw new Error(`Timeout waiting for ${selector}: ${text}; actual ${await page.locator(selector).textContent()}`);
};
try {
  ({ browser } = await launchBrowser());
  result.browser = browser.version();
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page = await context.newPage();
  page.setDefaultTimeout(90000);
  page.on('pageerror', e => result.errors.push(e.message));
  await page.goto(`${server.url}/tracks/art/`);
  assert.equal(await page.locator('#demo-frame').getAttribute('src'), 'about:blank');
  assert.equal(await page.locator('#ignite').isDisabled(), true);
  check('initially unloaded and controls disabled');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(out, 'narrow.png'), fullPage: true });
  check('390px viewport no horizontal overflow');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('#start-example').click();
  await waitText('#status', '45,808 / 45,808');
  assert.equal(await page.locator('#burning-count').textContent(), '0');
  assert.equal(await page.locator('#char-count').textContent(), '0');
  await page.waitForTimeout(1200);
  assert.equal(await page.locator('#time-label').textContent(), '模拟时间 0.00 s');
  await page.locator('#viewer').screenshot({ path: path.join(out, 'loaded.png') });
  check('synthetic scene loaded and initially paused', { points: 45808 });
  await page.locator('#context').fill('Automated UI integration check; synthetic scene, no audience.');
  await page.locator('#choice').fill('Test one explicit ignition, finite advance and reinitialization.');
  await page.locator('#note-form button[type=submit]').click();
  await page.locator('[data-stage=intervene]').click();
  await page.locator('#ignite').click();
  const ignited = Number((await page.locator('#burning-count').textContent()).replaceAll(',', ''));
  assert.ok(ignited > 0);
  assert.equal(await page.locator('#time-label').textContent(), '模拟时间 0.00 s');
  check('visible ignition affects scene without advancing time', { ignited });
  await page.locator('#advance').click();
  await waitText('#status', '本段推进完成');
  assert.equal(await page.locator('#time-label').textContent(), '模拟时间 1.00 s');
  assert.equal(await page.locator('#pause').isDisabled(), true);
  await page.locator('#viewer').screenshot({ path: path.join(out, 'after-one-second.png') });
  check('finite 60 step advance stops at one simulated second');
  await page.locator('#play').click();
  await page.waitForTimeout(400);
  await page.locator('#pause').click();
  const stoppedTime = await page.locator('#time-label').textContent();
  await page.waitForTimeout(700);
  assert.equal(await page.locator('#time-label').textContent(), stoppedTime);
  check('explicit pause stops time', { stoppedTime });
  await page.locator('#play').click();
  await page.waitForTimeout(200);
  await page.locator('[data-stage=revisit]').click();
  const stageStoppedTime = await page.locator('#time-label').textContent();
  await page.waitForTimeout(500);
  assert.equal(await page.locator('#time-label').textContent(), stageStoppedTime);
  check('stage switch stops time');
  await page.locator('#reset').click();
  assert.equal(await page.locator('#time-label').textContent(), '模拟时间 0.00 s');
  assert.equal(await page.locator('#burning-count').textContent(), '0');
  assert.equal(await page.locator('#char-count').textContent(), '0');
  assert.equal(await page.locator('#note-count').textContent(), '1 条记录');
  await page.locator('#viewer').screenshot({ path: path.join(out, 'reset.png') });
  check('reinitialization clears visible burn counters and preserves note');
  await page.locator('#camera-yaw').focus();
  await page.keyboard.press('Home');
  for (let i = 0; i < 48; i++) await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#yaw-value').textContent(), '60°');
  await page.locator('#viewer').screenshot({ path: path.join(out, 'yaw60.png') });
  check('angle control displays 60 degrees');
  await page.locator('#note-kind').selectOption('audience-observation');
  await page.locator('#observation').fill('UI validation placeholder, not a real audience statement.');
  await page.locator('#note-form button[type=submit]').click();
  await waitText('#save-status', '需要实际观看情境');
  assert.equal(await page.locator('#note-count').textContent(), '1 条记录');
  await page.locator('#note-kind').selectOption('author-draft');
  await page.locator('#observation').fill('');
  check('incomplete audience record rejected');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export').click();
  const download = await downloadPromise;
  await download.saveAs(path.join(out, 'journal.json'));
  const journal = JSON.parse(await fs.readFile(path.join(out, 'journal.json'), 'utf8'));
  assert.equal(journal.schema, 'vortex-gaussians-art-journal');
  assert.equal(journal.notes.length, 1);
  assert.equal(journal.notes[0].kind, 'author-draft');
  assert.equal(journal.currentSnapshot.scene.kind, 'synthetic-campfire-example');
  assert.equal(journal.currentSnapshot.parameters.yaw, 1 / 3);
  assert.ok(journal.events.some(e => e.type === 'ignite' && e.ignitedPoints === ignited));
  check('JSON export includes scene provenance, ignition and correct camera units');
  await page.reload();
  assert.equal(await page.locator('#note-count').textContent(), '1 条记录');
  assert.equal(await page.locator('#demo-frame').getAttribute('src'), 'about:blank');
  check('reload preserves journal without loading simulation');
  await page.locator('#local-ply').setInputFiles(path.join(repoRoot, 'static/test_scene.ply'));
  await waitText('#status', '45,808 / 45,808');
  assert.ok((await page.locator('#scene-label').textContent()).includes('本地资产'));
  assert.equal(await page.locator('#yaw-value').textContent(), '0°');
  check('local PLY input loads and resets angle');
  assert.deepEqual(result.errors, []);
  result.passed = true;
} catch (error) {
  result.passed = false; result.failure = error.stack;
  if (page) await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true }).catch(() => {});
  process.exitCode = 1;
} finally {
  if (browser) await browser.close();
  await server.close();
  await fs.writeFile(path.join(out, 'result.json'), JSON.stringify(result, null, 2) + '\n');
  console.log(JSON.stringify(result, null, 2));
}
