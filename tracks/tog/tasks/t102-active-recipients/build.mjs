import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Script} from 'node:vm';
const here=path.dirname(fileURLToPath(import.meta.url)),t97=path.join(here,'../t97-ordinary-cached-graph');
const text=await readFile(path.join(t97,'ordinary.js'),'utf8');
const demo=await readFile(path.resolve(here,'../../../../demo/index.html'),'utf8');
